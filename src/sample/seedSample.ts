import Storage from '../native/NativeStorage';
import Player from '../native/NativePlayer';
import AudioPipeline from '../native/NativeAudioPipeline';
import { db } from '../db/queries';
import bundle from './sampleMeeting.json';
import { SAMPLE_ID } from './sampleId';

/**
 * The bundled sample meeting, as an ordinary meeting in the person's own library.
 *
 * Every row a recorded meeting has: utterances, speakers, items with their anchors, the rule
 * minutes, the speech spans, and its audio on disk. So the transcript, the notes, the provenance
 * links and playback all work on it with nothing special-cased in them. What marks it is its id
 * (src/sample/sampleId.ts); there is no schema column for it.
 *
 * It does not go through CaptureController.start or the import path, which is where the Free
 * allowance takes a slot, so seeding it cannot cost one. Nothing here calls the licence module.
 *
 * Where the content comes from, and why none of it is typed by hand: sampleMeeting.json is
 * generated by scripts/make-sample-meeting.sh from the real pipeline's timings and the app's own
 * rule extractor, and a test pins that it still is.
 */

const GEN = 'rules@1'; // Minutes.RULES_GEN: what the free pass stamps on an item it wrote

type Stmt = { sql: string; params: unknown[] };

export async function sampleExists(): Promise<boolean> {
  const rows = await db.query<{ n: number }>('SELECT COUNT(*) AS n FROM meetings WHERE id = ?', [SAMPLE_ID]);
  return (rows[0]?.n ?? 0) > 0;
}

function statements(audioPath: string, now: number): Stmt[] {
  const out: Stmt[] = [
    // Cascades to every child table; here so the write is safe to repeat against a partial row.
    { sql: 'DELETE FROM meetings WHERE id = ?', params: [SAMPLE_ID] },
    {
      sql:
        'INSERT INTO meetings(id, title, created_at, duration_ms, language, status, tier_used, ' +
        "audio_path, audio_retained, items_migrated_at, end_reason) VALUES(?,?,?,?,?,'done','free',?,1,?,'stopped')",
      params: [SAMPLE_ID, bundle.title, now, bundle.durationMs, bundle.language, audioPath, now],
    },
  ];
  for (const s of bundle.speakers) {
    out.push({
      sql: 'INSERT INTO speakers(id, meeting_id, cluster_label, display_name) VALUES(?,?,?,?)',
      params: [s.id, SAMPLE_ID, s.clusterLabel, s.displayName],
    });
  }
  for (const u of bundle.utterances) {
    out.push({
      sql: 'INSERT INTO utterances(id, meeting_id, start_ms, end_ms, speaker_id, text) VALUES(?,?,?,?,?,?)',
      params: [u.id, SAMPLE_ID, u.startMs, u.endMs, u.speakerId, u.text],
    });
    out.push({
      sql: 'INSERT INTO segments(meeting_id, start_ms, end_ms) VALUES(?,?,?)',
      params: [SAMPLE_ID, u.startMs, u.endMs],
    });
  }
  bundle.minutes.forEach((m, i) => {
    out.push({
      sql: 'INSERT INTO minutes(id, meeting_id, kind, content_json, source) VALUES(?,?,?,?,?)',
      params: [`${SAMPLE_ID}:rule:${i}`, SAMPLE_ID, m.kind, m.content, 'rule'],
    });
  });
  for (const it of bundle.items) {
    out.push({
      sql:
        'INSERT INTO items(id, meeting_id, kind, text, review, gen_version, anchor_start_ms, ' +
        'anchor_end_ms, created_at, owner_json) VALUES(?,?,?,?,?,?,?,?,?,?)',
      params: [it.id, SAMPLE_ID, it.kind, it.text, 'suggested', GEN, it.anchorStartMs, it.anchorEndMs, now, it.ownerJson],
    });
    it.sources.forEach((s, ordinal) => {
      out.push({
        sql:
          'INSERT INTO item_sources(item_id, ordinal, start_ms, end_ms, char_start, char_end, utterance_id) ' +
          'VALUES(?,?,?,?,?,?,?)',
        params: [it.id, ordinal, s.startMs, s.endMs, s.charStart, s.charEnd, s.utteranceId],
      });
    });
    if (it.done) {
      out.push({
        sql: 'INSERT INTO item_done(meeting_id, item_id, done_at) VALUES(?,?,?)',
        params: [SAMPLE_ID, it.id, now],
      });
    }
  }
  return out;
}

/**
 * Put the sample in the library if it is not there; make it whole if it is.
 *
 * Idempotent. With the meeting present it writes no rows: it only puts the audio back if it has
 * gone (a restore, or anything that cleared the files) and brings the meeting out of the archive
 * if somebody archived it, which is what "See the sample again" has to mean.
 */
export async function seedSample(): Promise<{ created: boolean }> {
  if (await sampleExists()) {
    if (!(await Player.hasAudio(SAMPLE_ID).catch(() => false))) {
      const { path } = await Player.installSample(SAMPLE_ID);
      await db.query('UPDATE meetings SET audio_path = ?, audio_retained = 1 WHERE id = ?', [path, SAMPLE_ID]);
    }
    await db.query('UPDATE meetings SET archived_at = NULL WHERE id = ?', [SAMPLE_ID]);
    return { created: false };
  }
  // The audio first: a meeting row with no recording behind it would have source links that fail.
  const { path } = await Player.installSample(SAMPLE_ID);
  await Storage.transaction(JSON.stringify(statements(path, Date.now())));
  // Only native can write the search index. The sample is searchable like any meeting, and the
  // Library labels it so a hit on it is never mistaken for the person's own words.
  await Storage.reindex(SAMPLE_ID);
  return { created: true };
}

/** Remove the sample and its audio. Deleting it is always allowed; seedSample brings it back. */
export async function deleteSample(): Promise<void> {
  try {
    await AudioPipeline.discardAudio(SAMPLE_ID);
  } catch {
    // Already gone. Not a reason to keep the row.
  }
  await db.deleteMeeting(SAMPLE_ID);
}
